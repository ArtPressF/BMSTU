// Лабораторная работа №1, часть 1. Вариант 18.
// Вычислить sin x = x - x^3/3! + x^5/5! - ... + (-1)^(n-1) * x^(2n-1)/(2n-1)! + ...
// с точностью 10^-2, 10^-4, 10^-6 и определить, как меняется число итераций.
// Задача решена циклом с постусловием (do-while): первое слагаемое нужно
// сложить в любом случае, а точность проверяется после каждого слагаемого.
// Точное значение sin(x) в расчетах не используется, оно выводится
// только в конце для проверки.
#include <iostream>
#include <cmath>
using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian"); // Чтобы в консоли выводились русские буквы
    double x, e;
    cout << "x (в радианах) = ";
    cin >> x;
    cout << "Точность = "; // Например, 0.01, 0.0001, 0.000001
    cin >> e;

    double sum = 0; // Сумма ряда
    double a = x;   // Текущее слагаемое, при n = 1 равно x
    int k = 0;      // Число сложенных слагаемых (итераций)
    do
    {
        sum += a;
        k++;
        a *= -x * x / ((2 * k) * (2 * k + 1)); // Следующее слагаемое через предыдущее
    } while (fabs(a) >= e); // Пока модуль слагаемого >= точности цикл продолжается

    cout << "sin(x) = " << sum << ", итераций " << k << endl;
    cout << "Точное значение: sin(x) = " << sin(x) << endl;
    return 0;
}
