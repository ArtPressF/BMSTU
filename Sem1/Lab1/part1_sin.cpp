// Лабораторная работа №1, часть 1. Вариант 18.
// Вычислить sin x = x - x^3/3! + x^5/5! - ... + (-1)^(n-1) * x^(2n-1)/(2n-1)! + ...
// с точностью 10^-2, 10^-4, 10^-6 и определить, как меняется число итераций.
// Задача решена тремя видами цикла: с предусловием (while),
// с постусловием (do-while) и for. Точное значение sin(x) в расчетах
// не используется, оно выводится только в конце для проверки.
#include <iostream>
#include <cmath>
using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian"); // Чтобы в консоли выводились русские буквы
    double x;
    cout << "x (в радианах) = ";
    cin >> x;

    double eps[3] = { 1e-2, 1e-4, 1e-6 }; // Три значения точности

    for (int t = 0; t < 3; t++)
    {
        double e = eps[t];
        cout << endl << "Точность " << e << ":" << endl;

        // 1. Цикл с предусловием (while)
        double sum = 0; // Сумма ряда
        double a = x;   // Текущее слагаемое, при n = 1 равно x
        int k = 0;      // Число сложенных слагаемых (итераций)
        while (fabs(a) >= e) // Условие проверяется до выполнения тела цикла
        {
            sum += a;
            k++;
            a *= -x * x / ((2 * k) * (2 * k + 1)); // Следующее слагаемое через предыдущее
        }
        cout << "  while:    sin(x) = " << sum << ", итераций " << k << endl;

        // 2. Цикл с постусловием (do-while)
        sum = 0; a = x; k = 0;
        do // Тело цикла выполняется хотя бы один раз
        {
            sum += a;
            k++;
            a *= -x * x / ((2 * k) * (2 * k + 1));
        } while (fabs(a) >= e); // Условие проверяется после выполнения тела цикла
        cout << "  do-while: sin(x) = " << sum << ", итераций " << k << endl;

        // 3. Цикл for
        for (sum = 0, a = x, k = 0; fabs(a) >= e; a *= -x * x / ((2 * k) * (2 * k + 1))) // Инициализация, условие и модификация в заголовке
        {
            sum += a;
            k++;
        }
        cout << "  for:      sin(x) = " << sum << ", итераций " << k << endl;
    }

    // Точное значение, полученное встроенной функцией
    cout << endl << "Точное значение: sin(x) = " << sin(x) << endl;
    return 0;
}
