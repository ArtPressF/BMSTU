// Лабораторная работа №3, часть 2. Вариант 18.
// Базовый класс «прямоугольник», производный класс «прямоугольный параллелепипед».
// Два варианта переопределения функций:
//  1) статический полиморфизм (rect, box) - функции без virtual,
//     метод выбирается по типу указателя;
//  2) динамический полиморфизм (rectV, boxV) - функции с virtual в базовом классе,
//     метод выбирается по типу объекта.
#include <iostream>
#include <vector>
using namespace std;

// ---------- Статический полиморфизм ----------
class rect // Базовый класс - "Прямоугольник"
{
protected:
double a, b; // Длины сторон (статус доступа protected)
public:
rect(double a, double b) // Конструктор для инициализации полей
{
this->a=a; this->b=b;
}
double calc() // Вычисление площади
{
return a*b;
}
void print() // Метод для печати полей и площади
{
cout<<"rect: a="<<a<<" b="<<b<<" area="<<calc()<<endl; // Печатаем значения полей
}
};
class box: public rect // Производный класс - "Прямоугольный параллелепипед"
{
double h; // Новое поле - высота
public:
box(double a, double b, double h): // Конструктор
  rect(a, b) // Явный вызов конструктора базового класса
  {
  this->h=h;
  }
  double calc() // Переопределенная функция: объем вместо площади
  {
  return rect::calc()*h; // Вызов в переопределенной функции функции базового класса
  }
  void print() // Переопределенный метод print
  {
  cout<<"box: a="<<a<<" b="<<b<<" h="<<h<<" volume="<<calc()<<endl; // Печатаем поля и объем
  }
};

// ---------- Динамический полиморфизм ----------
class rectV // Базовый класс - "Прямоугольник"
{
protected:
double a, b; // Длины сторон
public:
rectV(double a, double b) // Конструктор для инициализации полей
{
this->a=a; this->b=b;
}
virtual double calc() // Вычисление площади (виртуальная функция)
{
return a*b;
}
virtual void print() // Метод для печати полей и площади (виртуальный)
{
cout<<"rect: a="<<a<<" b="<<b<<" area="<<calc()<<endl; // Печатаем значения полей
}
};
class boxV: public rectV // Производный класс - "Прямоугольный параллелепипед"
{
double h; // Новое поле - высота
public:
boxV(double a, double b, double h): // Конструктор
  rectV(a, b) // Явный вызов конструктора базового класса
  {
  this->h=h;
  }
  double calc() // Переопределенная виртуальная функция: объем
  {
  return rectV::calc()*h; // Вызов функции базового класса
  }
  void print() // Переопределенный метод print
  {
  cout<<"box: a="<<a<<" b="<<b<<" h="<<h<<" volume="<<calc()<<endl; // Печатаем поля и объем
  }
};

int main()
{
cout<<"1. Static polymorphism (no virtual)"<<endl;
rect r(2, 3); // Создается объект базового класса с вызовом конструктора
box bx(2, 3, 4); // Создается объект производного класса с вызовом конструктора
r.print(); // Вызов метода через объект
bx.print(); // Вызов метода через объект
rect *p; // Указатель типа базового класса
p=&r; // Настраиваем на объект базового класса
p->print(); // Вызов метода через указатель
p=&bx; // Настраиваем указатель на объект производного класса
       // (преобразование типа допустимо)
p->print(); // Вызывается метод класса rect: выбор по типу указателя
cout<<"p->calc()="<<p->calc()<<" (area, not volume)"<<endl<<endl; // Тоже функция базового класса

cout<<"2. Dynamic polymorphism (virtual)"<<endl;
rectV rv(2, 3); // Объект базового класса
boxV bv(2, 3, 4); // Объект производного класса
rectV *pv; // Указатель типа базового класса
pv=&rv; // Настраиваем на объект базового класса
pv->print(); // Вызывается метод класса rectV
pv=&bv; // Настраиваем на объект производного класса
pv->print(); // Вызывается метод класса boxV: выбор по типу объекта
cout<<"pv->calc()="<<pv->calc()<<" (volume)"<<endl<<endl; // Вызывается функция boxV

cout<<"3. Vector of pointers to objects of base and derived classes"<<endl;
rectV r1(2, 3), r2(5, 6); // Объекты базового класса
boxV b1(2, 3, 4), b2(1, 2, 3); // Объекты производного класса
vector<rectV*> v; // Вектор указателей на объекты базового класса
v.push_back(&r1); // В одном векторе указатели
v.push_back(&b1); // на объекты базового
v.push_back(&r2); // и производного
v.push_back(&b2); // классов
double sum=0; // Сумма площадей и объемов
for (int i = 0; i < v.size(); i++) // Перебираем все указатели вектора
{
v[i]->print(); // Печатаем данные объекта (динамический полиморфизм)
sum+=v[i]->calc(); // Для прямоугольника - площадь, для параллелепипеда - объем
}
cout<<"Sum of areas and volumes = "<<sum<<endl; // Вывод суммы
return 0;
}
